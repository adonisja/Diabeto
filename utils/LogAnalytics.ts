/**
 * Advanced analytics utilities for medical application insights
 */

export interface UserBehaviorPattern {
  userId: string;
  screenSequences: string[];
  averageSessionDuration: number;
  featureUsage: Record<string, number>;
  medicalDataEntryFrequency: Record<string, number>;
  peakUsageHours: number[];
}

export interface MedicalInsight {
  insightType: 'usage_pattern' | 'data_quality' | 'compliance_trend' | 'performance_metric';
  severity: 'info' | 'warning' | 'critical';
  description: string;
  recommendation: string;
  affectedUsers?: number;
  trend?: 'improving' | 'stable' | 'declining';
}

export interface PerformanceMetrics {
  screenLoadTimes: Record<string, number>;
  apiResponseTimes: Record<string, number>;
  errorRates: Record<string, number>;
  userSatisfactionScore: number;
  systemUtilization: number;
}

